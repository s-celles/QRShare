"""Regenerates the OpenTimestamps test fixtures of QRShare's paste board.

Provenance (no third-party example file is copied):
- pending.txt / pending.txt.ots: our own text file, stamped with the reference
  client (`ots stamp pending.txt`, opentimestamps-client 0.7.x) against the public
  calendars on 2026-11-05. This file is NOT regenerated by this script.
- everything else is built here with the reference library (python-opentimestamps
  0.4.x, `pip install opentimestamps`), used as a tool only:

    python3 generate.py   # from this directory

Outputs: complete.txt.ots, upgrade.bin, unsupported.ots, stamp-*.bin and
fixtures.json (hex values the tests compare against).
"""
import hashlib
import json

from opentimestamps.core.notary import BitcoinBlockHeaderAttestation, PendingAttestation, UnknownAttestation
from opentimestamps.core.op import OpAppend, OpPrepend, OpRIPEMD160, OpSHA1, OpSHA256
from opentimestamps.core.serialize import BytesDeserializationContext, BytesSerializationContext
from opentimestamps.core.timestamp import DetachedTimestampFile, Timestamp


def ser_file(f):
    ctx = BytesSerializationContext()
    f.serialize(ctx)
    return ctx.getbytes()


def ser_stamp(t):
    ctx = BytesSerializationContext()
    t.serialize(ctx)
    return ctx.getbytes()


def load(path):
    with open(path, "rb") as fd:
        return DetachedTimestampFile.deserialize(BytesDeserializationContext(fd.read()))


def pending_nodes(stamp):
    for msg, att in stamp.all_attestations():
        if isinstance(att, PendingAttestation):
            yield msg, att


def find(stamp, msg):
    if stamp.msg == msg:
        return stamp
    for sub in stamp.ops.values():
        found = find(sub, msg)
        if found is not None:
            return found
    return None


out = {}

# 1. Bitcoin-complete proof: graft a synthetic calendar answer for the
#    bob.btc.calendar.opentimestamps.org commitment of pending.txt.ots.
pending = load("pending.txt.ots")
uri = "https://bob.btc.calendar.opentimestamps.org"
commitment = next(msg for msg, att in pending_nodes(pending.timestamp) if att.uri == uri)
upgrade = Timestamp(commitment)
tip = upgrade.ops.add(OpAppend(bytes(range(16)))).ops.add(OpSHA256())
tip = tip.ops.add(OpPrepend(bytes(range(32, 64)))).ops.add(OpSHA256())
tip.attestations.add(BitcoinBlockHeaderAttestation(912345))
with open("upgrade.bin", "wb") as fd:
    fd.write(ser_stamp(upgrade))

complete = load("pending.txt.ots")
find(complete.timestamp, commitment).merge(upgrade)
with open("complete.txt.ots", "wb") as fd:
    fd.write(ser_file(complete))

# the same, without the pending attestation of the calendar that completed (ots prune-like)
find(complete.timestamp, commitment).attestations.remove(PendingAttestation(uri))
out["completePrunedHex"] = ser_file(complete).hex()
out["upgradeUri"] = uri
out["upgradeCommitmentHex"] = commitment.hex()
out["merkleRootInternalHex"] = tip.msg.hex()
out["merkleRootDisplayHex"] = tip.msg[::-1].hex()
out["pendingFileDigestHex"] = pending.file_digest.hex()

# 2. Unsupported operations and an unknown attestation.
digest = hashlib.sha256(b"unsupported").digest()
f = DetachedTimestampFile(OpSHA256(), Timestamp(digest))
f.timestamp.ops.add(OpSHA1()).attestations.add(PendingAttestation("https://alice.btc.calendar.opentimestamps.org"))
f.timestamp.ops.add(OpRIPEMD160()).ops.add(OpSHA256()).attestations.add(BitcoinBlockHeaderAttestation(1))
f.timestamp.attestations.add(UnknownAttestation(bytes.fromhex("0102030405060708"), b"payload"))
with open("unsupported.ots", "wb") as fd:
    fd.write(ser_file(f))
out["unsupportedDigestHex"] = digest.hex()

# 3. Stamping golden: QRShare's construction for one statement and two calendars.
statement = b"QPST golden statement"
D = hashlib.sha256(statement).digest()
nonce = bytes(range(100, 116))
root = hashlib.sha256(D + nonce).digest()
responses = []
for i, cal in enumerate(["https://alice.btc.calendar.opentimestamps.org", "https://finney.calendar.eternitywall.com"]):
    r = Timestamp(root)
    leaf = r.ops.add(OpAppend(bytes([i]) * 16)).ops.add(OpSHA256()).ops.add(OpPrepend(bytes([0x6a, 0xed, 0x05, 0x5f])))
    leaf.attestations.add(PendingAttestation(cal))
    raw = ser_stamp(r)
    with open("stamp-response-%d.bin" % i, "wb") as fd:
        fd.write(raw)
    responses.append(r)
golden = DetachedTimestampFile(OpSHA256(), Timestamp(D))
node = golden.timestamp.ops.add(OpAppend(nonce)).ops.add(OpSHA256())
for r in responses:
    node.merge(r)
with open("stamp-golden.ots", "wb") as fd:
    fd.write(ser_file(golden))
out["stampStatementHex"] = statement.hex()
out["stampNonceHex"] = nonce.hex()
out["stampRootHex"] = root.hex()

with open("fixtures.json", "w") as fd:
    json.dump(out, fd, indent=2, sort_keys=True)
    fd.write("\n")
